// Единственный перехват плагина: наблюдатель за CreateFileW в таблице импорта exe.
//
// Он ничего не подменяет — путь и результат вызова уходят движку как есть. Задачи две:
//   1) заметить запись в storage (счётчик epoch) — фоновый поток узнаёт о сохранении сразу,
//      а не на страховочном обходе;
//   2) не дать нашему читателю стать причиной отказа движку: слои открываются с share=0,
//      и если в этот миг файл читаем мы, открытие повторяется, пока читатель не отпустит.
//
// Почему именно эта точка (docs/research/dayz-persistence.md, разд. 1.3, 3.3, 5, 6):
// через импорт CreateFileW образа идут и слои CE (FileServerST), и файлы модов (enf FS),
// и встроенный в exe SQLite (его таблица системных вызовов ссылается на тот же слот);
// импорт есть во всех разобранных сборках 1.29–1.30+. Перехват не обязателен для
// корректности: без него работает обход каталога по таймеру.
#pragma once
#include <cstdint>
#include <string>

#include "fs.hpp"

namespace dpdb::watch {

enum class Kind {
    Other,
    Storage,   // под охраняемым каталогом
    Foreign,   // под каким-то другим storage_<id>: признак неверно определённых путей
};

// До install(). cwd — рабочий каталог процесса: часть путей движок передаёт от него.
void configure(const fs::Path& storage_dir, const fs::Path& cwd);

// Горячий путь перехвата: без выделений памяти и блокировок.
Kind classify(const wchar_t* path);

// Поставить наблюдателя в таблицу импорта модуля. Число слотов; 0 — импорта нет (перехват
// не работает, остаётся обход по таймеру). Повторный вызов безвреден.
int install(void* module);

std::uint64_t epoch();     // открытий на запись под storage
std::uint64_t foreign();   // открытий на запись в чужой storage_<id>
std::wstring foreign_sample();
std::uint64_t retries();   // повторов открытия из-за нашего читателя

}  // namespace dpdb::watch
